        public DataTable DanhsachDVT()
        {
// Code cũ: OleDbCommand cmd = new OleDbCommand("SELECT * FROM DON_VI_TINH");
            SqlCommand cmd = new SqlCommand("SELECT * FROM DON_VI_TINH");
            m_Ds.Load(cmd);

            return m_Ds.ResultTable;
        }


/// <summary>
/// [REFACTORING GURU]
/// - Code Smell: Tight Coupling với OleDb và Primitive Obsession trong tầng truy cập dữ liệu
