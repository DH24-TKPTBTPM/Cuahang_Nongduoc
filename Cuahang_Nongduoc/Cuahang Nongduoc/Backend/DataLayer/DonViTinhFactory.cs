        public DataTable LayDVT(int id)
        {
// Code cũ: OleDbCommand cmd = new OleDbCommand("SELECT * FROM DON_VI_TINH WHERE ID = @id");
            SqlCommand cmd = new SqlCommand("SELECT * FROM DON_VI_TINH WHERE ID = @id");
// Code cũ: cmd.Parameters.Add("id", OleDbType.Integer).Value = id;
            cmd.Parameters.Add("id", SqlDbType.Int).Value = id;
            m_Ds.Load(cmd);
            return m_Ds.ResultTable;
        }
