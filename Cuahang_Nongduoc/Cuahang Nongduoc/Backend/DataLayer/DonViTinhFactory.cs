/// - Kiểm tra (Reviewer/Tester): QA Team
/// - Ngày chỉnh sửa (Date): 30/10/2026
/// </summary>
        public bool Save()
        {
            return m_Ds.ExecuteNoneQuery() > 0;
        }
    }
