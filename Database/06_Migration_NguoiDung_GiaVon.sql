-- Bổ sung bảng NGUOI_DUNG và cột GIA_VON cho CSDL CuahangNongduoc trên SQL Server
USE CuahangNongduoc;
GO

IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_NAME = 'NGUOI_DUNG')
BEGIN
    CREATE TABLE NGUOI_DUNG (
        ID INT IDENTITY(1,1) PRIMARY KEY,
        TEN_DANG_NHAP NVARCHAR(100) NOT NULL UNIQUE,
        MATKHAU NVARCHAR(255) NOT NULL,
        SALT NVARCHAR(255) NULL,
        ROLE NVARCHAR(20) NOT NULL,
        HOTEN NVARCHAR(150) NULL,
        IS_ACTIVE BIT NOT NULL DEFAULT 1,
        MUST_CHANGE_PWD BIT NOT NULL DEFAULT 0,
        CREATED_AT DATETIME DEFAULT GETDATE(),
        UPDATED_AT DATETIME DEFAULT GETDATE()
    );
    PRINT N'Đã tạo bảng NGUOI_DUNG thành công.';
END
GO

IF NOT EXISTS (SELECT * FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'CHI_TIET_PHIEU_BAN' AND COLUMN_NAME = 'GIA_VON')
BEGIN
    ALTER TABLE CHI_TIET_PHIEU_BAN ADD GIA_VON DECIMAL(18, 2) NULL;
    PRINT N'Đã thêm cột GIA_VON vào bảng CHI_TIET_PHIEU_BAN.';
END
GO

IF EXISTS (SELECT * FROM NGUOI_DUNG WHERE TEN_DANG_NHAP = 'vodichbatphuong')
BEGIN
    UPDATE NGUOI_DUNG
    SET MATKHAU = 'vodichbatphuong123', SALT = NULL, ROLE = 'admin', IS_ACTIVE = 1, MUST_CHANGE_PWD = 0, UPDATED_AT = GETDATE()
    WHERE TEN_DANG_NHAP = 'vodichbatphuong';
    PRINT N'Đã cập nhật tài khoản vodichbatphuong.';
END
ELSE
BEGIN
    INSERT INTO NGUOI_DUNG (TEN_DANG_NHAP, MATKHAU, SALT, ROLE, HOTEN, IS_ACTIVE, MUST_CHANGE_PWD, CREATED_AT, UPDATED_AT)
    VALUES ('vodichbatphuong', 'vodichbatphuong123', NULL, 'admin', N'Vô Địch Bát Phương', 1, 0, GETDATE(), GETDATE());
    PRINT N'Đã tạo tài khoản vodichbatphuong.';
END
GO

